// Measures where the head sits in every driver headshot (public/img/drivers/{year}/{CODE}.png) and
// writes lib/headshot-metrics.generated.ts, so avatars can be centred on the face.
//
//   node scripts/assets/measure_headshots.mjs
//
// For each image: the opaque pixels of the top part of the figure (head and neck, before the
// shoulders widen) give the horizontal centre `cx`, the top of the hair `top` and the width of
// the head `w`, all as fractions of the image.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const DIR = join(ROOT, "public", "img", "drivers");
const result = {};
const rows = [];

for (const year of readdirSync(DIR).sort()) {
  for (const file of readdirSync(join(DIR, year)).sort()) {
    if (!file.endsWith(".png")) continue;
    const { data, info } = await sharp(join(DIR, year, file))
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    const { width, height } = info;
    const opaque = (x, y) => data[(y * width + x) * 4 + 3] > 40;
    let top = -1;
    for (let y = 0; y < height && top < 0; y += 1) {
      for (let x = 0; x < width; x += 1) {
        if (opaque(x, y)) {
          top = y;
          break;
        }
      }
    }
    // Head band: from the top of the hair down to 30 % of the image height below it.
    const bottom = Math.min(height - 1, top + Math.round(height * 0.3));
    let min = width;
    let max = 0;
    let sum = 0;
    let count = 0;
    for (let y = top; y <= bottom; y += 1) {
      for (let x = 0; x < width; x += 1) {
        if (opaque(x, y)) {
          if (x < min) min = x;
          if (x > max) max = x;
          sum += x;
          count += 1;
        }
      }
    }
    const cx = (min + max) / 2 / width;
    const centroid = sum / count / width;
    const key = `${year}/${file.replace(".png", "")}`;
    // The middle of the extent is robust against one-sided hair or a turned head.
    result[key] = [Number(((cx + centroid) / 2).toFixed(3)), Number((top / height).toFixed(3)), Number(((max - min) / width).toFixed(3))];
    rows.push([key, ...result[key]]);
  }
}
writeFileSync(
  join(ROOT, "lib", "headshot-metrics.generated.ts"),
  "// Generated by scripts/assets/measure_headshots.mjs: [centre x, top, head width] as image fractions.\n" +
    `export const HEADSHOT_METRICS: Record<string, [number, number, number]> = ${JSON.stringify(result)};\n`,
);
const cxs = rows.map((r) => r[1]);
console.log(rows.length, "images; cx min/max", Math.min(...cxs), Math.max(...cxs));
console.log("most off-centre:", rows.sort((a, b) => Math.abs(b[1] - 0.5) - Math.abs(a[1] - 0.5)).slice(0, 8).map((r) => r.join(" ")).join(" | "));
